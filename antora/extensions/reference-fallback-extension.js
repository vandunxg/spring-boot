'use strict'

/**
 * Gives unresolved references a sensible target instead of a dead link.
 *
 * Two fallbacks, applied in order, by wrapping ContentCatalog#resolveResource
 * (which ContentCatalog#resolvePage delegates to, so xrefs, includes and the
 * include-code:: macro all go through it):
 *
 * 1. Locale fallback. A page of a translated component that references
 *    something the translation does not carry yet - an untranslated module, or
 *    the sample code that only the English component mirrors - resolves against
 *    the source locale instead.
 *
 * 2. External module fallback. Content generated by the Spring Boot build
 *    (javadoc, the Actuator REST API, the auto-configuration listings) is not
 *    part of this documentation-only fork, so references into those modules
 *    point at the official published documentation. Only page references are
 *    redirected this way; a reference naming a family (partial$, example$,
 *    attachment$) is left unresolved, because its content has to be read.
 *
 * Playbook configuration:
 *
 *   - require: ./antora/extensions/reference-fallback-extension.js
 *     component_fallbacks:
 *     - component: vi
 *       fallback: boot
 *     external_modules:
 *     - module: api
 *       url: 'https://docs.spring.io/spring-boot/api'
 */
module.exports.register = function ({ config = {} }) {
  const componentFallbacks = new Map(
    (config.componentFallbacks || []).map(({ component, fallback }) => {
      if (!(component && fallback)) {
        throw new Error('each component_fallbacks entry needs a component and a fallback')
      }
      return [component, fallback]
    })
  )
  const externalModules = new Map(
    (config.externalModules || []).map(({ module: module_, url }) => {
      if (!(module_ && url)) throw new Error('each external_modules entry needs a module and a url')
      return [module_, url.replace(/\/$/, '')]
    })
  )

  this.once('contentClassified', ({ contentCatalog }) => {
    const resolveResource = contentCatalog.resolveResource.bind(contentCatalog)
    contentCatalog.resolveResource = (spec, context = {}, defaultFamily, permittedFamilies) => {
      const resolved = resolveResource(spec, context, defaultFamily, permittedFamilies)
      if (resolved) return resolved
      const fallbackComponent = componentFallbacks.get(context.component)
      if (fallbackComponent) {
        const inFallback = resolveResource(
          spec,
          Object.assign({}, context, { component: fallbackComponent }),
          defaultFamily,
          permittedFamilies
        )
        if (inFallback) return inFallback
      }
      if (defaultFamily !== 'page' || spec.includes('$')) return resolved
      return resolveExternal(spec, context, externalModules)
    }
  })
}

function resolveExternal (spec, context, externalModules) {
  const ref = parseSpec(spec)
  if (!ref) return undefined
  if (ref.component && ref.component !== context.component) return undefined
  const base = externalModules.get(ref.module || context.module)
  if (!base) return undefined
  const relative = ref.relative.replace(/\.adoc$/, '.html')
  return {
    src: {
      family: 'page',
      component: context.component,
      version: context.version,
      module: ref.module || context.module,
      relative,
    },
    pub: { url: `${base}/${relative}` },
  }
}

function parseSpec (spec) {
  const segments = spec.split(':')
  // A bare path is relative to the module of the page holding the reference.
  if (segments.length === 1) return { relative: segments[0] }
  if (segments.length === 2) return { module: segments[0], relative: segments[1] }
  if (segments.length === 3) return { component: segments[0], module: segments[1], relative: segments[2] }
  return undefined
}
